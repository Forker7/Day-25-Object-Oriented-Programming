class bike:


    def __init__(self,maxspeed,milage):
        self.maxspeed = maxspeed
        self.milage = milage

urbike = bike(140,35)

print("Your Max Speed is ",urbike.maxspeed)
print("Your milage is ",urbike.milage)


mybike = bike(250,18)

print("Your Max Speed is ",mybike.maxspeed)
print("Your milage is ",mybike.milage)
